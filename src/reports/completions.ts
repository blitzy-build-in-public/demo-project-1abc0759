/**
 * Completions report: the number of tasks completed on each UTC day of an inclusive range.
 *
 * The repository returns only the days that have completions; this module fills in the rest with
 * zeros so the table, and the chart built from it, show every day exactly once. Pure: no I/O and no
 * clock.
 */

import type { DayCount } from '../db/types';
import type { DateRange, IsoDate } from '../shared/dates';
import { eachDay } from '../shared/dates';

/**
 * The completions report for one inclusive range, ready for the reports page.
 *
 * `days` is typed structurally rather than as `DayCount[]` so the web layer can consume it without
 * importing `src/db`, which its layer rules forbid.
 */
export interface CompletionsReport {
  /** The reported range, both ends included. */
  range: DateRange;
  /** One entry per day of the range, in ascending order; days without completions count 0. */
  days: { day: IsoDate; count: number }[];
  /** Sum of the `days` counts, so it always agrees with the table. */
  total: number;
}

/**
 * Builds the zero-filled completions report for a range.
 *
 * Every day from `range.from` to `range.to` appears once, in order, with the count of tasks whose
 * `completed_at` falls on that UTC day. A task reopened after completion has `completed_at = NULL`,
 * so the repository's query does not count it. Rows for days outside the range are ignored, and a
 * day reported twice has its counts summed. When `total` is 0 the reports page adds "No tasks were
 * completed in this period."; that message belongs to the template, not to this report.
 *
 * The caller passes a range already validated by `parseDateRange`, so it spans at most 366 days.
 * The days are generated by `eachDay`, which never computes the day after `range.to`, so a range
 * ending `9999-12-31` terminates normally.
 *
 * @param range - The inclusive range to report.
 * @param rows - Completions per UTC day from `TasksRepo.completionsByDay`.
 * @returns The report with one entry per day of the range and the total of those entries.
 * @throws RangeError when either end of `range` is not a valid {@link IsoDate}.
 */
export function zeroFillCompletions(
  range: DateRange,
  rows: readonly DayCount[],
): CompletionsReport {
  const countsByDay = new Map<IsoDate, number>();
  for (const row of rows) {
    countsByDay.set(row.day, (countsByDay.get(row.day) ?? 0) + row.count);
  }

  const days = eachDay(range.from, range.to).map((day) => ({
    day,
    count: countsByDay.get(day) ?? 0,
  }));
  const total = days.reduce((sum, entry) => sum + entry.count, 0);

  return { range: { from: range.from, to: range.to }, days, total };
}
